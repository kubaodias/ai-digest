#!/usr/bin/env node
// npm run deploy [-- --skip-tests]
//
// Builds and ships the function with telnyx-edge, using our own entry point
// (src/index.ts, the v1 API):
//   1. checks .env and runs the tests
//   2. registers the function on the first deploy (telnyx-edge new-func)
//   3. stores the settings as Telnyx secrets (values in the request body, never on a command line)
//   4. writes .edge/ (telnyx.toml + entry) and ships it
//   5. records the public URL (and ships again on the first deploy, since emails need it)
//   6. pushes your digest definitions from digests/
//   7. applies the Agent Memory summary instructions

import { randomBytes } from "node:crypto";
import { existsSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync, mkdirSync } from "node:fs";
import { tmpdir, homedir } from "node:os";
import { join } from "node:path";
import { agentApi, edgeDir, loadEnv, readState, root, run, say, setEnvValue, telnyx, writeState } from "./lib.mjs";

const args = new Set(process.argv.slice(2));
let env = loadEnv();
const name = env.FUNCTION_NAME || "ai-digest";

// 1. settings and tests
const missing = ["DIGEST_EMAIL_FROM", "DIGEST_EMAIL_TO"].filter((k) => !env[k]);
if (missing.length) {
  console.error(`Missing in .env: ${missing.join(", ")}. Copy .env.example to .env and fill it in (docs/SETUP.md).`);
  process.exit(1);
}
if (!args.has("--skip-tests")) {
  say("Running tests");
  run("npm", ["test", "--silent"]);
}

// 2. the function
let state = readState();
if (!state.functionId && existsSync(join(root, "agent.json"))) {
  // Deployed with telnyx-acp before 0.2.0: keep the same function (and its actors' state).
  const d = JSON.parse(readFileSync(join(root, "agent.json"), "utf8")).deployed;
  if (d?.functionId) state = { functionId: d.functionId, functionName: d.functionName ?? name, publicUrl: d.mountUrl };
}
if (!state.functionId) {
  say(`Registering the function "${name}"`);
  const scratch = mkdtempSync(join(tmpdir(), "ai-digest-new-func-"));
  try {
    mkdirSync(join(scratch, "empty"));
    run("telnyx-edge", ["new-func", "--name", name, "--from-dir", join(scratch, "empty")], { cwd: scratch, quiet: true });
    const toml = readFileSync(join(scratch, name, "func.toml"), "utf8");
    state.functionId = toml.match(/func_id\s*=\s*"([^"]+)"/)?.[1];
    state.functionName = name;
    if (!state.functionId) throw new Error("telnyx-edge new-func didn't report the function's id");
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
}
writeState(state);

// 3. secrets
say("Storing settings as Telnyx secrets");
const existing = new Set((await telnyx(env, "GET", "/compute/secrets?page[size]=250")).data?.map((s) => s.secret_name) ?? []);
async function setSecret(key, value) {
  await telnyx(env, "POST", "/compute/secrets", { secret_name: key, secret_value: value });
  console.log(`  ✓ ${key}`);
}
// The operator key: from .env, else the one telnyx-acp saved before 0.2.0, else a new one. Kept in .env for the scripts.
if (!env.AGENT_AUTH_KEY) {
  let legacy;
  try {
    const keys = JSON.parse(readFileSync(join(process.env.TELNYX_ACP_HOME ?? join(homedir(), ".telnyx-acp"), "auth-keys.json"), "utf8"));
    legacy = state.publicUrl ? keys[new URL(state.publicUrl).origin] : undefined;
  } catch {}
  setEnvValue("AGENT_AUTH_KEY", legacy ?? randomBytes(32).toString("hex"));
  env = loadEnv();
  console.log(`  ✓ AGENT_AUTH_KEY written to .env (${legacy ? "the key telnyx-acp had saved" : "new"})`);
}
await setSecret("AGENT_AUTH_KEY", env.AGENT_AUTH_KEY);
await setSecret("DIGEST_EMAIL_FROM", env.DIGEST_EMAIL_FROM);
await setSecret("DIGEST_EMAIL_TO", env.DIGEST_EMAIL_TO);
// The link-signing key: never rotated here (that would break links in emails already sent).
if (env.FEEDBACK_KEY) await setSecret("FEEDBACK_KEY", env.FEEDBACK_KEY);
else if (!existing.has("FEEDBACK_KEY")) await setSecret("FEEDBACK_KEY", randomBytes(32).toString("hex"));
if (env.ADMIN_EMAIL) await setSecret("ADMIN_EMAIL", env.ADMIN_EMAIL);
const knownUrl = env.PUBLIC_URL || state.publicUrl;
if (knownUrl) await setSecret("PUBLIC_URL", knownUrl);

// 4. build and ship
const SECRETS = ["AGENT_AUTH_KEY", "DIGEST_EMAIL_FROM", "DIGEST_EMAIL_TO", "FEEDBACK_KEY", "PUBLIC_URL", ...(env.ADMIN_EMAIL || existing.has("ADMIN_EMAIL") ? ["ADMIN_EMAIL"] : [])];
function writeBuild() {
  mkdirSync(edgeDir, { recursive: true });
  writeFileSync(
    join(edgeDir, "telnyx.toml"),
    [
      `# Generated by npm run deploy. Do not edit; never commit.`,
      `name = "${state.functionName}"`,
      `main = "index.ts"`,
      `compatibility_date = "2026-10-01"`,
      ``,
      `[edge_compute]`,
      `func_id = "${state.functionId}"`,
      `func_name = "${state.functionName}"`,
      ``,
      `[[actors]]`,
      `binding = "AI_DIGEST"`,
      `type = "AiDigest"`,
      ``,
      `[telnyx]`,
      `binding = "TELNYX"`,
      ...SECRETS.flatMap((s) => [``, `[[secrets]]`, `binding = "${s}"`, `name = "${s}"`]),
      ``,
    ].join("\n"),
  );
  writeFileSync(join(edgeDir, "index.ts"), `// Generated by npm run deploy: the entry is src/index.ts.\nexport * from "../src/index.ts";\nexport { default } from "../src/index.ts";\n`);
  writeFileSync(join(edgeDir, "package.json"), JSON.stringify({ name: `${state.functionName}-build`, private: true, type: "module" }, null, 2) + "\n");
}
function ship() {
  writeBuild();
  run("telnyx-edge", ["ship", "--from-dir", edgeDir, "--yes", "--timeout", "25m"]);
}
say(`Shipping ${state.functionName} (${state.functionId})`);
ship();

// 5. public URL
const inspected = run("telnyx-edge", ["inspect", state.functionName], { quiet: true });
const url = inspected.match(/Invoke URL\s+(\S+)/)?.[1];
if (!url) throw new Error("couldn't read the function's Invoke URL from telnyx-edge inspect");
if (url !== state.publicUrl || url !== knownUrl) {
  state.publicUrl = url;
  writeState(state);
  await setSecret("PUBLIC_URL", url);
  if (url !== knownUrl) {
    say(`Public URL is ${url}: shipping again so emails link to it`);
    ship();
  }
}
const health = await fetch(`${url}/v1/health`).then((r) => r.json()).catch((e) => ({ error: String(e) }));
console.log(`  ${url}/v1/health → ${JSON.stringify(health)}`);

// 6. digests
const digestsDir = join(root, "digests");
const files = existsSync(digestsDir) ? readdirSync(digestsDir).filter((f) => f.endsWith(".md")) : [];
if (files.length) {
  say(`Pushing ${files.length} digest definition(s) from digests/`);
  for (const f of files) {
    const id = f.replace(/\.md$/, "");
    const r = await agentApi(env, "PUT", `/v1/digests/${id}`, readFileSync(join(digestsDir, f), "utf8"), { raw: true });
    console.log(`  ✓ ${id}${r.changed ? "" : " (unchanged)"}`);
  }
} else {
  say("No digests/ yet: copy one from examples/digests/ (see docs/SETUP.md)");
}

// 7. Agent Memory summary instructions
say("Agent Memory summary instructions");
try {
  await telnyx(env, "GET", "/ai/memory/namespaces/ai-digest");
} catch {
  await telnyx(env, "POST", "/ai/memory/namespaces", { name: "ai-digest" });
  console.log("  ✓ created memory namespace ai-digest");
}
const instructions = readFileSync(join(root, "docs/memory-summary-instructions.md"), "utf8").replace(/^<!--[\s\S]*?-->\s*/, "").trim();
await telnyx(env, "PATCH", "/ai/memory/namespaces/ai-digest/settings", { summary: { instructions } });
console.log("  ✓ applied");

say(`Done.\n  Your digests: ${url}/v1/app\n  Start one:    npm run digests -- run ${files[0]?.replace(/\.md$/, "") ?? "<digest>"}`);
